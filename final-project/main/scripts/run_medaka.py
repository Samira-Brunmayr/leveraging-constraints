"""This script runs medaka on the given assembly using its fastq basecalls.
Assumes minimap2, samtools, htslib, bcfts etc are in PATH
"""

import argparse
import os
import subprocess
from typing import Optional

from main.scripts.constants import TEST_DATA, TRAIN_DATA


def medaka(fastq_path: str, assembly_path: str, out_dir: str, threads: int):
    command = [
        "medaka_consensus",
        "-i",
        fastq_path,
        "-d",
        assembly_path,
        "-o",
        out_dir,
        "-t",
        str(threads),
        "-m",
        "r941_min_hac_g507",
    ]
    process = subprocess.Popen(command)
    process.communicate()


def main(
    path: str,
    threads: int,
    verbose: bool,
    is_wick: bool,
    output_dir: Optional[str] = None,
    assembly_path: Optional[str] = None,
):
    # if not is-wick ensure that assembly path and output dir are provided
    if not is_wick:
        if output_dir is None or assembly_path is None:
            raise ValueError(
                "--assembly-path and --output-dir must be provided if not --is-wick"
            )
        if verbose:
            print("Running Medaka...")
        medaka(
            fastq_path=path,
            assembly_path=assembly_path,
            out_dir=output_dir,
            threads=threads,
        )

    elif is_wick:
        if assembly_path is not None or output_dir is not None:
            raise ValueError(
                "Do not use --assembly-path or --output-dir with --is-wick"
            )
        # --path is root of folder created by basecall script
        folders = [os.path.join(path, f) for f in os.listdir(path) if f != "genomes"]

        for directory in folders:
            folder_name = os.path.basename(directory)

            if verbose:
                print("\nProcessing {}".format(folder_name))

            # if test then make sure we have a flye_out folder and basecalls.fastq
            if (
                not os.path.isfile(os.path.join(directory, "basecalls.fastq"))
                and folder_name in TEST_DATA
            ):
                raise FileNotFoundError(
                    f"Couldn't locate basecalls.fastq for {folder_name}"
                )

            if (
                not os.path.isdir(os.path.join(directory, "flye_out"))
                and folder_name in TEST_DATA
            ):
                raise FileNotFoundError(
                    f"Couldn't locate flye_out directory for {folder_name}, have you run generate_assemblies.py?"
                )

            if folder_name in TRAIN_DATA:
                if verbose:
                    print("Train data, skipping...")
            elif folder_name in TEST_DATA:
                if not os.path.isfile(
                    os.path.join(directory, "flye_out/assembly.fasta")
                ):
                    raise FileNotFoundError(
                        f"Could not find assembly.fasta in {folder_name}"
                    )
                if verbose:
                    print(f"Running Medaka {folder_name}")
                medaka(
                    fastq_path=os.path.join(directory, "basecalls.fastq"),
                    assembly_path=os.path.join(directory, "flye_out/assembly.fasta"),
                    out_dir=os.path.join(directory, "medaka_out"),
                    threads=threads,
                )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--path",
        type=str,
        required=True,
        help="Path to basecalled fastq or to root basecalled dir if --is-wick",
    )
    parser.add_argument(
        "--threads",
        type=int,
        default=2,
        help="Number of threads to use for Medaka",
    )
    parser.add_argument("--verbose", action="store_true", help="Toggle verbosity")
    parser.add_argument(
        "--is-wick",
        action="store_true",
        help="If --path points to a wick structured basecalled root dir rather than a fastq",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        help="Output directory for Medaka if not --is-wick",
    )
    parser.add_argument(
        "--assembly-path",
        type=str,
        help="Path to assembly FASTA generated by Flye (or blank if --is-wick)",
    )

    parser.add_argument

    args = parser.parse_args()
    main(
        path=args.path,
        threads=args.threads,
        verbose=args.verbose,
        is_wick=args.is_wick,
        output_dir=args.output_dir,
        assembly_path=args.assembly_path,
    )
